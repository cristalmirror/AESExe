pub struct Aes {
    rounds: usize,
    keys: Vec<[u8; 16]>,
}

impl Aes {
    pub fn new(key: &[u8]) -> io::Result<Self> {
        let (nk, rounds) = match key.len() {
            16 => (4, 10),
            24 => (6, 12),
            32 => (8, 14),
            n => {
                return validate_key(
                    key,
                    if n < 20 {
                        16
                    } else if n < 28 {
                        24
                    } else {
                        32
                    },
                )
                .map(|_| unreachable!());
            }
        };
        let total = 16 * (rounds + 1);
        let mut exp = vec![0u8; total];
        exp[..key.len()].copy_from_slice(key);
        let mut rcon = 1u8;
        let mut i = key.len();
        while i < total {
            let mut t = [exp[i - 4], exp[i - 3], exp[i - 2], exp[i - 1]];
            if i.is_multiple_of(nk * 4) {
                t.rotate_left(1);
                t.iter_mut().for_each(|b| *b = SBOX[*b as usize]);
                t[0] ^= rcon;
                rcon = xtime(rcon);
            } else if nk == 8 && i % 32 == 16 {
                t.iter_mut().for_each(|b| *b = SBOX[*b as usize]);
            }
            for b in t {
                exp[i] = exp[i - nk * 4] ^ b;
                i += 1;
            }
        }
        let keys = exp
            .chunks_exact(16)
            .map(|c| c.try_into().unwrap())
            .collect();
        Ok(Self { rounds, keys })
    }
}

fn xtime(x: u8) -> u8 {
    (x << 1) ^ if x & 0x80 != 0 { 0x1b } else { 0 }
}
fn mul(mut a: u8, mut b: u8) -> u8 {
    let mut p = 0;
    for _ in 0..8 {
        if b & 1 != 0 {
            p ^= a
        }
        a = xtime(a);
        b >>= 1;
    }
    p
}
fn add(s: &mut [u8; 16], k: &[u8; 16]) {
    for i in 0..16 {
        s[i] ^= k[i]
    }
}
fn shift(s: &mut [u8; 16]) {
    let x = *s;
    for r in 0..4 {
        for c in 0..4 {
            s[4 * c + r] = x[4 * ((c + r) % 4) + r]
        }
    }
}
fn inv_shift(s: &mut [u8; 16]) {
    let x = *s;
    for r in 0..4 {
        for c in 0..4 {
            s[4 * c + r] = x[4 * ((c + 4 - r) % 4) + r]
        }
    }
}
fn mix(s: &mut [u8; 16]) {
    for c in s.chunks_exact_mut(4) {
        let x = [c[0], c[1], c[2], c[3]];
        c[0] = mul(x[0], 2) ^ mul(x[1], 3) ^ x[2] ^ x[3];
        c[1] = x[0] ^ mul(x[1], 2) ^ mul(x[2], 3) ^ x[3];
        c[2] = x[0] ^ x[1] ^ mul(x[2], 2) ^ mul(x[3], 3);
        c[3] = mul(x[0], 3) ^ x[1] ^ x[2] ^ mul(x[3], 2)
    }
}
fn inv_mix(s: &mut [u8; 16]) {
    for c in s.chunks_exact_mut(4) {
        let x = [c[0], c[1], c[2], c[3]];
        c[0] = mul(x[0], 14) ^ mul(x[1], 11) ^ mul(x[2], 13) ^ mul(x[3], 9);
        c[1] = mul(x[0], 9) ^ mul(x[1], 14) ^ mul(x[2], 11) ^ mul(x[3], 13);
        c[2] = mul(x[0], 13) ^ mul(x[1], 9) ^ mul(x[2], 14) ^ mul(x[3], 11);
        c[3] = mul(x[0], 11) ^ mul(x[1], 13) ^ mul(x[2], 9) ^ mul(x[3], 14)
    }
}

impl BlockCipher for Aes {
    fn block_size(&self) -> usize {
        16
    }
    fn encrypt_block(&mut self, input: &[u8], output: &mut [u8]) {
        let mut s: [u8; 16] = input[..16].try_into().unwrap();
        add(&mut s, &self.keys[0]);
        for r in 1..self.rounds {
            s.iter_mut().for_each(|b| *b = SBOX[*b as usize]);
            shift(&mut s);
            mix(&mut s);
            add(&mut s, &self.keys[r]);
        }
        s.iter_mut().for_each(|b| *b = SBOX[*b as usize]);
        shift(&mut s);
        add(&mut s, &self.keys[self.rounds]);
        output[..16].copy_from_slice(&s)
    }
    fn decrypt_block(&mut self, input: &[u8], output: &mut [u8]) {
        let mut s: [u8; 16] = input[..16].try_into().unwrap();
        add(&mut s, &self.keys[self.rounds]);
        inv_shift(&mut s);
        s.iter_mut().for_each(|b| *b = INV_SBOX[*b as usize]);
        for r in (1..self.rounds).rev() {
            add(&mut s, &self.keys[r]);
            inv_mix(&mut s);
            inv_shift(&mut s);
            s.iter_mut().for_each(|b| *b = INV_SBOX[*b as usize]);
        }
        add(&mut s, &self.keys[0]);
        output[..16].copy_from_slice(&s)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    fn hex(s: &str) -> Vec<u8> {
        (0..s.len())
            .step_by(2)
            .map(|i| u8::from_str_radix(&s[i..i + 2], 16).unwrap())
            .collect()
    }
    #[test]
    fn nist_vectors() {
        for (k, e) in [
            (
                "000102030405060708090a0b0c0d0e0f",
                "69c4e0d86a7b0430d8cdb78070b4c55a",
            ),
            (
                "000102030405060708090a0b0c0d0e0f1011121314151617",
                "dda97ca4864cdfe06eaf70a0ec0d7191",
            ),
            (
                "000102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f",
                "8ea2b7ca516745bfeafc49904b496089",
            ),
        ] {
            let p = hex("00112233445566778899aabbccddeeff");
            let mut a = Aes::new(&hex(k)).unwrap();
            let mut out = [0; 16];
            a.encrypt_block(&p, &mut out);
            assert_eq!(out.as_slice(), hex(e));
            let mut back = [0; 16];
            a.decrypt_block(&out, &mut back);
            assert_eq!(back.as_slice(), p)
        }
    }
}
